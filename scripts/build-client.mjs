/**
 * Assemble client.js from the sources.
 *
 * The plugin ships as one plain-JS bundle: the sidebar runtime loads it through
 * `window.__ModuleLoader__`, which only provides `require('react')` — there is no
 * module table entry for our own files and no bundler at install time. So the pure
 * conversion code in src/convert.js is inlined ahead of the UI in src/client-ui.js
 * and exposed to it as the `FormulaConvert` namespace, and src/symbols.js becomes
 * `FormulaSymbols` the same way.
 *
 * Run: node scripts/build-client.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))

const read = (relative) => readFileSync(join(root, relative), 'utf8')

/** The names a module publishes; also the last statement in that file. */
const EXPORT_BLOCK = /export\s*\{([\s\S]*?)\}\s*$/

/** Read one source module and split it into its body and its exported names. */
const splitModule = (relative, exportsPattern) => {
  const source = read(relative)
  const match = exportsPattern.exec(source)
  if (match === null) throw new Error(`${relative} must end with its export list`)
  const names = match[1]
    .split(',')
    .map((name) => name.trim())
    .filter((name) => name.length > 0)
  if (names.length === 0) throw new Error(`${relative} exports nothing`)
  return { body: source.slice(0, match.index).trimEnd(), names }
}

const convert = splitModule('src/convert.js', EXPORT_BLOCK)

/* symbols.js uses inline `export const`, so collect those names and strip the keyword. */
const symbolsSource = read('src/symbols.js')
const symbolsNames = [...symbolsSource.matchAll(/^export\s+(?:const|function|class)\s+([A-Za-z_$][\w$]*)/gmu)]
  .map((hit) => hit[1])
if (symbolsNames.length === 0) throw new Error('src/symbols.js exports nothing')
const symbolsBody = symbolsSource.replace(/^export\s+(?=(?:const|function|class)\s)/gmu, '').trimEnd()

const namespaceOf = (name, names) =>
  `const ${name} = Object.freeze({\n${names.map((one) => `  ${one},`).join('\n')}\n})`

const convertNamespace = namespaceOf('FormulaConvert', convert.names)
const symbolsNamespace = namespaceOf('FormulaSymbols', symbolsNames)

const uiSource = read('src/client-ui.js').trim()

/* A duplicate top-level binding would silently shadow one half with the other. */
const declared = (source) => {
  const names = new Set()
  const pattern = /^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gmu
  let hit = pattern.exec(source)
  while (hit !== null) {
    names.add(hit[1])
    hit = pattern.exec(source)
  }
  return names
}

const uiNames = declared(uiSource)
for (const [file, body] of [['src/convert.js', convert.body], ['src/symbols.js', symbolsBody]]) {
  const clashes = [...declared(body)].filter((name) => uiNames.has(name))
  if (clashes.length > 0) {
    throw new Error(`src/client-ui.js redeclares ${file} helpers: ${clashes.join(', ')}`)
  }
}

const bundle = `/* dsh-formula-editor — generated by scripts/build-client.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: 'dsh-formula-editor',
  factory(require) {
    const React = require('react');

${convert.body}

${convertNamespace}

${symbolsBody}

${symbolsNamespace}

${uiSource}
  },
});
`

writeFileSync(join(root, 'client.js'), bundle, 'utf8')

const bytes = Buffer.byteLength(bundle, 'utf8')
console.log(`client.js written: ${bytes} bytes`)
console.log(`  inlined convert.js: ${convert.names.length} exports`)
console.log(`  inlined symbols.js: ${symbolsNames.length} exports`)
